// Island kit (Lane 3): writes src/island/Hub/Environment/KitManifest.luau from the Blender
// build's manifest.json, so the game knows each mesh's bounds and placement data without the
// mesh files (which stay in Car-Hop-Art, outside Git).
//   node assets/island/kit/write_manifest.js C:\Users\agert\Documents\Car-Hop-Art\island-kit
const fs = require("fs");
const path = require("path");

const kitDir = process.argv[2];
if (!kitDir) throw new Error("usage: node write_manifest.js <island-kit folder>");
const manifest = JSON.parse(fs.readFileSync(path.join(kitDir, "manifest.json"), "utf8"));
manifest.sort((a, b) => (a.name < b.name ? -1 : 1));

const num = (n) => String(Math.round(n * 1000) / 1000);
const vec = (v) => `Vector3.new(${v.map(num).join(", ")})`;
const lines = [];
for (const m of manifest) {
	const meta = Object.entries(m.meta || {})
		.filter(([, v]) => typeof v === "number")
		.map(([k, v]) => `${k} = ${num(v)}`)
		.join(", ");
	lines.push(
		`\t${m.name} = { family = "${m.family}", group = "${m.family_group}", triangles = ${m.triangles}, ` +
			`min = ${vec(m.bounds[0])}, max = ${vec(m.bounds[1])}, meta = { ${meta} } },`,
	);
}

const out = `--!strict
-- GENERATED by assets/island/kit/write_manifest.js from the island kit build; do not edit.
-- Per mesh: family, triangle count, bounds in the mesh's own space (y 0 is the ground line) and
-- placement data from the recipe (height, trunk_radius, canopy_base, sink, root_reach).

export type Entry = {
\tfamily: string,
\tgroup: string,
\ttriangles: number,
\tmin: Vector3,
\tmax: Vector3,
\tmeta: { [string]: number },
}

local KitManifest: { [string]: Entry } = {
${lines.join("\n")}
}

return KitManifest
`;
const target = path.join(__dirname, "..", "..", "..", "src", "island", "Hub", "Environment", "KitManifest.luau");
fs.writeFileSync(target, out);
console.log(`wrote ${manifest.length} entries to ${target}`);
