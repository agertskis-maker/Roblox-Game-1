// Island kit (Lane 3): writes src/island/Hub/Environment/KitManifest.luau from the Blender
// build's manifest.json, so the game knows each mesh's bounds and placement data without the
// mesh files (which stay in Car-Hop-Art, outside Git).
//   node assets/island/kit/write_manifest.js C:\Users\agert\Documents\Car-Hop-Art\island-kit [more kit folders...]
// Several folders merge into one manifest (the Task 4 families build into their own folders); a
// mesh name may appear only once. Meta keeps plain numbers (nested keys joined with ".", list items
// by 1-based index) and, as points, every [x, y, z] in Blender mesh-local axes converted to Roblox
// mesh-local (x, z, -y), relative to the mesh origin like the rest of the meta.
const fs = require("fs");
const path = require("path");

const kitDirs = process.argv.slice(2);
if (kitDirs.length === 0) throw new Error("usage: node write_manifest.js <island-kit folder> [more folders]");
const manifest = [];
const seen = new Set();
for (const dir of kitDirs) {
	for (const m of JSON.parse(fs.readFileSync(path.join(dir, "manifest.json"), "utf8"))) {
		if (seen.has(m.name)) throw new Error("mesh name in two kit folders: " + m.name);
		seen.add(m.name);
		manifest.push(m);
	}
}
manifest.sort((a, b) => (a.name < b.name ? -1 : 1));

const num = (n) => String(Math.round(n * 1000) / 1000);
const vec = (v) => `Vector3.new(${v.map(num).join(", ")})`;
const isPoint = (v) => Array.isArray(v) && v.length === 3 && v.every((x) => typeof x === "number");
function flatten(value, key, nums, pts, tags) {
	if (typeof value === "number") nums.push([key, value]);
	else if (typeof value === "string") tags.push([key, value]);
	else if (isPoint(value)) pts.push([key, value]);
	else if (Array.isArray(value)) value.forEach((v, i) => flatten(v, key ? `${key}.${i + 1}` : String(i + 1), nums, pts, tags));
	else if (value && typeof value === "object") for (const [k, v] of Object.entries(value)) flatten(v, key ? `${key}.${k}` : k, nums, pts, tags);
}
const ident = (k) => (/^[A-Za-z_][A-Za-z0-9_]*$/.test(k) ? k : `[${JSON.stringify(k)}]`);

const lines = [];
for (const m of manifest) {
	const nums = [];
	const pts = [];
	const tags = [];
	flatten(m.meta || {}, "", nums, pts, tags);
	const meta = nums.map(([k, v]) => `${ident(k)} = ${num(v)}`).join(", ");
	const points = pts.map(([k, v]) => `${ident(k)} = ${vec([v[0], v[2], -v[1]])}`).join(", ");
	// only short names are kept as tags (sign face names and the like), not prose notes
	const tagText = tags
		.filter(([k, v]) => /(^|\.)name$/.test(k) && v.length <= 40)
		.map(([k, v]) => `${ident(k)} = ${JSON.stringify(v)}`)
		.join(", ");
	lines.push(
		`\t${m.name} = { family = "${m.family}", group = "${m.family_group}", triangles = ${m.triangles}, ` +
			`min = ${vec(m.bounds[0])}, max = ${vec(m.bounds[1])}, meta = { ${meta} }, points = { ${points} }, tags = { ${tagText} } },`,
	);
}

const out = `--!strict
-- GENERATED by assets/island/kit/write_manifest.js from the island kit build; do not edit.
-- Per mesh: family, triangle count, bounds in the mesh's own space (y 0 is the ground line),
-- placement numbers from the recipe (height, trunk_radius, canopy_base, sink, root_reach, ...;
-- nested recipe keys joined with ".") and attachment points (Roblox mesh-local, from the origin).

export type Entry = {
\tfamily: string,
\tgroup: string,
\ttriangles: number,
\tmin: Vector3,
\tmax: Vector3,
\tmeta: { [string]: number },
\tpoints: { [string]: Vector3 },
\ttags: { [string]: string }, -- recipe names, e.g. sign_faces.1.name
}

local KitManifest: { [string]: Entry } = {
${lines.join("\n")}
}

return KitManifest
`;
const target = path.join(__dirname, "..", "..", "..", "src", "island", "Hub", "Environment", "KitManifest.luau");
fs.writeFileSync(target, out);
console.log(`wrote ${manifest.length} entries from ${kitDirs.length} folder(s) to ${target}`);
